/**
 * Disclosure arrow. Points right when collapsed and rotates 90° to
 * point down when `open`, so one glyph covers both states. Decorative;
 * the interactive parent owns the toggle semantics.
 */
export function Chev({ open = false }: { open?: boolean }) {
  return (
    <svg
      className={open ? 'v3-chev v3-chev--open' : 'v3-chev'}
      width="10"
      height="10"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2.2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
    >
      <path d="m9 18 6-6-6-6" />
    </svg>
  );
}
